create table if not exists recipes (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  category text,
  created_at timestamptz not null default now()
);

create table if not exists recipe_ingredients (
  id bigint generated by default as identity primary key,
  recipe_id uuid not null references recipes(id) on delete cascade,
  amount text,
  unit text,
  name text not null
);

create table if not exists recipe_steps (
  id bigint generated by default as identity primary key,
  recipe_id uuid not null references recipes(id) on delete cascade,
  step_number integer not null,
  description text not null
);

create table if not exists shopping_items (
  id bigint generated by default as identity primary key,
  name text not null,
  amount text,
  unit text,
  checked boolean not null default false,
  source_recipe_id uuid references recipes(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists recipe_stack (
  id bigint generated by default as identity primary key,
  recipe_id uuid not null references recipes(id) on delete cascade,
  position integer not null,
  created_at timestamptz not null default now()
);

alter table recipes enable row level security;
alter table recipe_ingredients enable row level security;
alter table recipe_steps enable row level security;
alter table shopping_items enable row level security;
alter table recipe_stack enable row level security;

-- Prototype policies: public access so the first deployment works without auth.
-- Add auth/user_id columns + per-user RLS before using this for private data.
create policy "public read recipes" on recipes for select using (true);
create policy "public insert recipes" on recipes for insert with check (true);
create policy "public read ingredients" on recipe_ingredients for select using (true);
create policy "public insert ingredients" on recipe_ingredients for insert with check (true);
create policy "public read steps" on recipe_steps for select using (true);
create policy "public insert steps" on recipe_steps for insert with check (true);
create policy "public all shopping" on shopping_items for all using (true) with check (true);
create policy "public all stack" on recipe_stack for all using (true) with check (true);
